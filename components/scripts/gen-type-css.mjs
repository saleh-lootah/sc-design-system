#!/usr/bin/env node
/**
 * Generates the type "mixins" used inside shadow roots from the design tokens.
 *
 *   design-system/tokens/typography.json  ->  src/styles/type/<role>.css  (one file per role)
 *                                          ->  src/styles/type.css        (documentation + every role)
 *
 * Shadow DOM can't see the global .sc-type-* classes, so each role becomes five custom
 * properties set on :host, switched to the Arabic scale by :host(:lang(ar)):
 *
 *   --type-<role>-family  --type-<role>-weight  --type-<role>-size
 *   --type-<role>-leading --type-<role>-tracking
 *
 * plus a ready-made `.type-<role>` class that applies all five.
 *
 * Runs before build, start and test (npm "pre" scripts). No dependencies.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const tokensFile = join(root, '..', 'tokens', 'typography.json');
const outDir = join(root, 'src', 'styles');
const roleDir = join(outDir, 'type');

/*
 * The token file has separate Latin and Arabic scales, and not every role exists in both.
 * Where a role is missing from one script we borrow the nearest role from that script.
 * These gaps are reported upstream; when the tokens add the role, delete its line here.
 */
/** Arabic-only roles: the Latin role whose size and leading they use. */
const LATIN_FALLBACK = {
  hint: 'body-s',
  error: 'body-s',
};
/** Latin-only roles: the Arabic role they switch to (null keeps the Latin metrics, tracking 0). */
const ARABIC_FALLBACK = {
  'display-xl': 'display-l',
  'heading-xl': 'heading-l',
  'title-l': 'heading-m',
  'title-m': 'title-s',
  'label-s': 'caption',
  eyebrow: 'caption',
  'caption-s': 'caption',
  value: 'body-m',
  'numeral-l': null, // numerals are always Latin digits
};

const tokens = JSON.parse(readFileSync(tokensFile, 'utf8'));
const latin = roles(tokens.type.latin);
const arabic = roles(tokens.type.arabic);

function roles(group) {
  return Object.fromEntries(Object.entries(group).filter(([k]) => !k.startsWith('$')));
}

/** "{font.family.bold}" -> "var(--sc-font-family-bold)" */
function ref(value) {
  const m = /^\{font\.(family|weight)\.([\w-]+)\}$/.exec(String(value));
  if (!m) throw new Error(`Unexpected typography reference: ${value}`);
  return `var(--sc-font-${m[1]}-${m[2]})`;
}

function latinSet(role) {
  const own = latin[role];
  const metricsRole = own ? role : LATIN_FALLBACK[role];
  if (!metricsRole || !latin[metricsRole]) throw new Error(`No Latin metrics for role "${role}"; add it to LATIN_FALLBACK`);
  const face = (own ?? arabic[role]).$value;
  return {
    family: ref(face.fontFamily),
    weight: ref(face.fontWeight),
    size: `var(--sc-text-latin-${metricsRole})`,
    leading: `var(--sc-leading-latin-${metricsRole})`,
    tracking: `var(--sc-tracking-latin-${metricsRole})`,
    note: own ? null : `Latin uses ${metricsRole} metrics (no Latin "${role}" token)`,
  };
}

function arabicSet(role) {
  if (arabic[role]) {
    const v = arabic[role].$value;
    return {
      family: ref(v.fontFamily),
      weight: ref(v.fontWeight),
      size: `var(--sc-text-arabic-${role})`,
      leading: `var(--sc-leading-arabic-${role})`,
      tracking: '0',
      note: null,
    };
  }
  if (!(role in ARABIC_FALLBACK)) throw new Error(`No Arabic metrics for role "${role}"; add it to ARABIC_FALLBACK`);
  const borrowed = ARABIC_FALLBACK[role];
  if (borrowed === null) {
    return { tracking: '0', note: `Arabic keeps the Latin metrics (no Arabic "${role}" token), tracking 0` };
  }
  const v = arabic[borrowed].$value;
  return {
    family: ref(v.fontFamily),
    weight: ref(v.fontWeight),
    size: `var(--sc-text-arabic-${borrowed})`,
    leading: `var(--sc-leading-arabic-${borrowed})`,
    tracking: '0',
    note: `Arabic uses ${borrowed} (no Arabic "${role}" token)`,
  };
}

const HEADER = '/* Generated by scripts/gen-type-css.mjs from design-system/tokens/typography.json. Do not edit. */';
const PROPS = ['family', 'weight', 'size', 'leading', 'tracking'];

function roleCss(role) {
  const l = latinSet(role);
  const a = arabicSet(role);
  const notes = [l.note, a.note].filter(Boolean);
  const decl = (set) =>
    PROPS.filter((p) => set[p] !== undefined)
      .map((p) => `  --type-${role}-${p}: ${set[p]};`)
      .join('\n');
  return [
    HEADER,
    `/* Role: ${role}${notes.length ? `. ${notes.join('. ')}.` : ''} */`,
    `:host {\n${decl(l)}\n}`,
    `:host(:lang(ar)) {\n${decl(a)}\n}`,
    `.type-${role} {
  font-family: var(--type-${role}-family);
  font-weight: var(--type-${role}-weight);
  font-size: var(--type-${role}-size);
  line-height: var(--type-${role}-leading);
  letter-spacing: var(--type-${role}-tracking);
}`,
    '',
  ].join('\n');
}

const allRoles = [...Object.keys(latin), ...Object.keys(arabic).filter((r) => !latin[r])];

mkdirSync(roleDir, { recursive: true });
for (const f of readdirSync(roleDir)) if (f.endsWith('.css')) unlinkSync(join(roleDir, f));
for (const role of allRoles) writeFileSync(join(roleDir, `${role}.css`), roleCss(role));

const doc = `${HEADER}
/*
 * TYPE ROLES INSIDE SHADOW ROOTS
 *
 * The global .sc-type-* classes in tokens.css can't reach into a shadow root, so each
 * type role is also available as five custom properties, set on :host and switched to
 * the Arabic scale (with letter-spacing 0) by :host(:lang(ar)):
 *
 *   --type-<role>-family   --type-<role>-weight   --type-<role>-size
 *   --type-<role>-leading  --type-<role>-tracking
 *
 * PATTERN (in a component's CSS file)
 *
 *   1. Import only the roles the component uses, from src/styles/type/:
 *
 *        @import '../../styles/type/title-s.css';
 *        @import '../../styles/type/label-m.css';
 *
 *   2. Either put the ready-made class on the element in TSX:
 *
 *        <span class="label type-title-s">…</span>
 *
 *      or apply the properties yourself, e.g. when the role depends on a prop:
 *
 *        .label {
 *          font-family: var(--type-title-s-family);
 *          font-weight: var(--type-title-s-weight);
 *          font-size: var(--type-title-s-size);
 *          line-height: var(--type-title-s-leading);
 *          letter-spacing: var(--type-title-s-tracking);
 *        }
 *
 *   That's all: Arabic switches automatically when the closest [lang] is "ar".
 *   Never set font-size, line-height or letter-spacing to anything else.
 *
 * This file imports every role; it's for prototypes and the playground. Components
 * import single roles so each shadow root only carries what it uses.
 *
 * Roles: ${allRoles.join(', ')}
 */
${allRoles.map((r) => `@import './type/${r}.css';`).join('\n')}
`;
writeFileSync(join(outDir, 'type.css'), doc);

console.log(`gen-type-css: ${allRoles.length} roles -> src/styles/type/*.css and src/styles/type.css`);
