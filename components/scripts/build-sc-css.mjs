#!/usr/bin/env node
/**
 * Builds sc.css, the one document stylesheet a page links (architecture §3.4):
 *
 *   @layer sc.reset, sc.tokens, sc.base, sc.components, sc.utilities;
 *   @layer sc.tokens     { design-system/dist/css/tokens.css }
 *   @font-face …           src/global/fonts.css (cannot be layered)
 *   @layer sc.base       { src/global/base.css }
 *   @layer sc.components { src/global/components.css }
 *   @layer sc.utilities  { src/global/shadow.css, the same helpers shadow roots adopt }
 *
 * Writes src/global/generated/sc.css (git-ignored). stencil.config.ts copies it next to the
 * loader (dist/sc-components/sc.css) and into the playground (www/build/sc.css), beside
 * assets/fonts/, so the font URLs resolve. Runs before build, start and test.
 *
 * Unlayered service CSS beats every sc layer, so services override without !important or
 * specificity games. A layered framework orders itself with `@layer base, sc, components, …`.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const g = (f) => join(root, 'src', 'global', f);
const tokensFile = join(root, '..', 'dist', 'css', 'tokens.css');

/** Comment and whitespace removal only: safe for every construct used in these files. */
function minify(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/:\s*;/g, ':\u0000;') // an empty custom property ("--x: ;", a space toggle) keeps its space
    .replace(/\s+/g, ' ')
    .replace(/\s*([{};,>])\s*/g, '$1')
    .replace(/:\s+(?=[^;{}]*;)/g, ':') // "prop: value;" -> "prop:value;" (never matches selectors)
    .replace(/;}/g, '}')
    .replace(/\u0000/g, ' ')
    .trim();
}

let tokens;
try {
  tokens = readFileSync(tokensFile, 'utf8');
} catch {
  console.error('build-sc-css: dist/css/tokens.css is missing. Run `npm run build` at the repository root first.');
  process.exit(1);
}

const layer = (name, css) => `@layer ${name}{${minify(css)}}`;
const out = [
  '/* Shared Channels design system v2 · sc.css · generated by components/scripts/build-sc-css.mjs */',
  '@layer sc.reset,sc.tokens,sc.base,sc.components,sc.utilities;',
  layer('sc.tokens', tokens),
  minify(readFileSync(g('fonts.css'), 'utf8')),
  layer('sc.base', readFileSync(g('base.css'), 'utf8')),
  layer('sc.components', readFileSync(g('components.css'), 'utf8')),
  layer('sc.utilities', readFileSync(g('shadow.css'), 'utf8')),
].join('\n');

mkdirSync(g('generated'), { recursive: true });
writeFileSync(g('generated/sc.css'), out + '\n');
console.log(`build-sc-css: src/global/generated/sc.css ${(out.length / 1024).toFixed(1)} KiB raw, ${(gzipSync(out, { level: 9 }).length / 1024).toFixed(2)} KiB gzip`);
