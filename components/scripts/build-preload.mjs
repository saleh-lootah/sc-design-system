#!/usr/bin/env node
/**
 * Writes the lazy loader's preload hints (architecture §3.6, Standard PERF-11) after the build:
 *
 *   dist/sc-components/sc-preload.json   { "core": "p-….js", "page": ["p-….entry.js", …] }
 *   dist/sc-components/sc-preload.html   the <link rel="modulepreload"> tags, paths relative
 *                                         to dist/sc-components/
 *
 * Without hints the lazy loader is a four-step waterfall: the loader, then the runtime core it
 * imports, then a component bundle once the runtime sees the tag, then that bundle's shared
 * chunks. On Slow 4G each step is a round trip. The hints name the core and the page-shell
 * bundle (the bundle that holds sc-page, with the chrome every page has) and the chunks it
 * imports, so they all download in parallel with the loader. File names carry a content hash,
 * so a CMS includes the generated snippet rather than copying names into a template.
 *
 * Run by `npm run build` (postbuild). Needs a production build: `stencil test` writes a dev
 * build into dist/.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist', 'sc-components');
const read = (f) => readFileSync(join(dir, f), 'utf8');
const imports = (src) => [...new Set([...src.matchAll(/(?:from|import)\s*"\.\/([^"]+\.js)"/g)].map((m) => m[1]))];

const loader = read('sc-components.esm.js');
const core = imports(loader)[0];
if (!core) {
  console.error('build-preload: dist/sc-components is not a production build. Run `npm run build`.');
  process.exit(1);
}

// The bundle table in bootstrapLazy(): ["p-<hash>",[[flags,"sc-tag",…],…]], one entry per bundle.
const starts = [...loader.matchAll(/\["(p-[A-Za-z0-9_-]+)",\[\[/g)];
const bundleOf = (tag) => {
  for (const [i, m] of starts.entries()) {
    const body = loader.slice(m.index, starts[i + 1]?.index ?? loader.length);
    if (body.includes(`,"${tag}"`)) return `${m[1]}.entry.js`;
  }
  return undefined;
};
const shell = bundleOf('sc-page');
if (!shell || !existsSync(join(dir, shell))) {
  console.error('build-preload: no lazy bundle holds sc-page.');
  process.exit(1);
}

// The shell bundle and everything it imports, except the core (listed first on its own).
const page = [];
const walk = (f) => {
  if (f === core || page.includes(f)) return;
  page.push(f);
  for (const d of imports(read(f))) walk(d);
};
walk(shell);

writeFileSync(join(dir, 'sc-preload.json'), JSON.stringify({ core, page }, null, 2) + '\n');
writeFileSync(
  join(dir, 'sc-preload.html'),
  [
    '<!-- Generated by components/scripts/build-preload.mjs. Paths are relative to dist/sc-components/. -->',
    ...[core, ...page].map((f) => `<link rel="modulepreload" href="${f}">`),
  ].join('\n') + '\n',
);
console.log(`build-preload: core ${core} + ${page.length} page-shell modules`);
