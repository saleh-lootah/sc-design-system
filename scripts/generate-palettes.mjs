#!/usr/bin/env node
// Generates the colour tokens from tokens/source/color.source.json:
//   tokens/palette.json     every tonal palette, OKLAB, tone = CIELAB L*
//   tokens/color.json       light role tokens, as references into the palettes
//   tokens/color.dark.json  dark role tokens, as references into the palettes
// Plain Node (ESM), no dependencies. Run: node scripts/generate-palettes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { TOKENS_DIR, ROOT } from './lib/tokens.mjs';
import { lch } from './lib/oklab.mjs';
import { solveTone, roundLab, yToTone } from './lib/tonal.mjs';
import { luminance } from './lib/oklab.mjs';

const SOURCE = 'tokens/source/color.source.json';
const src = JSON.parse(readFileSync(join(ROOT, SOURCE), 'utf8'));
const GENERATED = `Generated by scripts/generate-palettes.mjs from ${SOURCE}. Do not edit.`;
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')));

// ---------------------------------------------------------------- palettes

const palette = { $type: 'color' };
const report = [];
for (const [name, def] of Object.entries(src.palettes)) {
  const isNeutral = name === 'neutral';
  const tones = isNeutral ? src.tones.neutral : src.tones.chromatic;
  let hue, seedC;
  if (def.seed) [, seedC, hue] = lch(...def.seed);
  else [hue, seedC] = [def.hue, def.chroma];
  const curve = { ...strip(src.chromaCurve), ...(def.chromaCurve ?? {}) };
  const group = { $description: def.description };
  for (const t of tones) {
    const want = isNeutral ? seedC : seedC * (curve[t] ?? 1);
    const solved = solveTone(t, hue, want);
    const components = roundLab(solved);
    group[t] = {
      $value: { colorSpace: 'oklab', components },
      $extensions: { 'sc.tone': t, ...(solved.clamped ? { 'sc.gamutClamped': true } : {}) },
    };
    if (solved.clamped) report.push(`${name}-${t} chroma clamped to sRGB (${solved.C.toFixed(3)} of ${want.toFixed(3)})`);
  }
  if (def.seed) {
    const seedTone = yToTone(luminance(...def.seed));
    group.$extensions = { 'sc.seed': { components: def.seed, tone: Number(seedTone.toFixed(1)), hue: Number(hue.toFixed(1)), chroma: Number(seedC.toFixed(4)) } };
  }
  palette[name] = group;
}

// ---------------------------------------------------------------- roles

const ref = (pal, tone) => {
  if (!palette[pal]?.[tone]) throw new Error(`palette.${pal}.${tone} is not generated; add the tone to ${SOURCE}`);
  return `{palette.${pal}.${tone}}`;
};

function roles(mode) {
  const color = { $type: 'color' };
  for (const [role, [pal, light, dark, use]] of Object.entries(strip(src.roles))) {
    color[role] = { $value: ref(pal, mode === 'light' ? light : dark), ...(mode === 'light' ? { $description: use } : {}) };
  }
  for (const [role, [lightLab, lightA, darkLab, darkA, use]] of Object.entries(strip(src.alphaRoles))) {
    const [c, a] = mode === 'light' ? [lightLab, lightA] : [darkLab, darkA];
    color[role] = { $value: { colorSpace: 'oklab', components: c, ...(a < 1 ? { alpha: a } : {}) }, ...(mode === 'light' ? { $description: use } : {}) };
  }

  const channelTone = (spec, action) => {
    if (typeof spec === 'number') return spec;
    if (spec === 'action') return action;
    const m = /^action-(\d+)$/.exec(spec);
    if (m) return action - Number(m[1]);
    throw new Error(`Bad channel tone ${spec}`);
  };
  const channel = { $type: 'color' };
  const channels = strip(src.channels);
  for (const [ch, { palette: pal, action }] of Object.entries(channels)) {
    channel[ch] = {};
    for (const [role, [light, dark, use]] of Object.entries(strip(src.channelRoles))) {
      const tone = mode === 'light' ? channelTone(light, action) : dark;
      channel[ch][role] = { $value: ref(pal, tone), ...(mode === 'light' ? { $description: use } : {}) };
    }
  }
  // The active channel: components read color.channel.*, which the CSS rebinds per [data-channel].
  color.channel = {};
  for (const role of Object.keys(strip(src.channelRoles))) {
    color.channel[role] = {
      $value: `{channel.${src.defaultChannel}.${role}}`,
      ...(mode === 'light' ? { $description: `Active channel: ${src.channelRoles[role][2]}` } : {}),
    };
  }
  return { color, channel };
}

// ---------------------------------------------------------------- write

function write(file, json) {
  const path = join(TOKENS_DIR, file);
  writeFileSync(path, JSON.stringify(json, null, 2) + '\n');
  console.log(`  wrote ${relative(ROOT, path)}`);
}

console.log('Generating palettes');
write('palette.json', { $description: GENERATED, palette });
write('color.json', { $description: GENERATED, ...roles('light') });
write('color.dark.json', { $description: GENERATED, $extensions: { mode: 'dark' }, ...roles('dark') });
for (const r of report) console.log(`  note: ${r}`);
